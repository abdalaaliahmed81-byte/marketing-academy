 const name=unique('API طالب')
 await register(page,name)
 expect(await page.evaluate(()=>document.cookie)).not.toContain('ma_session')
 expect(await page.evaluate(async()=>(await indexedDB.databases()).some(db=>db.name?.startsWith('marketing-academy-user-')))).toBe(false)
