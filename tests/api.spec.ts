test('a shared cookie changing to another account cannot copy stale tab data into that account',async({context,page})=>{
 await register(page,unique('API Alice'))
 await page.getByRole('link',{name:'مسار التعلّم',exact:true}).click()
 const other=await context.newPage()
 await register(other,unique('API Bob'))
 await page.getByRole('button',{name:/^ملاحظات:/}).first().click()
 await page.getByRole('dialog').getByRole('textbox').fill('must never enter Bob account')
 await expect(page.getByRole('button',{name:'ادخل إلى الأكاديمية'})).toBeVisible()
 await other.getByRole('link',{name:'مسار التعلّم',exact:true}).click()
 await other.getByRole('button',{name:/^ملاحظات:/}).first().click()
 await expect(other.getByRole('dialog').getByRole('textbox')).toHaveValue('')
 await other.close()
})
test('a delayed save acknowledgement from a closed account cannot log out the next account',async({page})=>{
 await register(page,unique('Delayed Alice'))
 let intercept=true,captured!:()=>void,release!:()=>void
 const gotRequest=new Promise<void>(resolve=>{captured=resolve}),barrier=new Promise<void>(resolve=>{release=resolve})
 await page.route('**/api/command',async route=>{
  const body=route.request().postDataJSON()
  if(intercept&&body.command==='commit'){intercept=false;const response=await route.fetch();captured();await barrier;await route.fulfill({response})}else await route.continue()
 })
 await page.getByRole('button',{name:'المظهر الداكن',exact:true}).click();await gotRequest
 await page.getByRole('button',{name:'خروج',exact:true}).click()
 const bob=unique('Delayed Bob')
 await page.getByRole('button',{name:'إنشاء حساب',exact:true}).click()
 await page.getByLabel('اسم المستخدم',{exact:true}).fill(bob)
 await page.getByLabel('كلمة المرور',{exact:true}).fill(password)
 await page.getByLabel('تأكيد كلمة المرور',{exact:true}).fill(password)
 await page.getByRole('button',{name:'أنشئ حسابي'}).click()
 await page.getByRole('button',{name:'ابدأ التعلّم',exact:true}).click()
 release()
 await expect(page.getByRole('button',{name:'خروج',exact:true})).toBeVisible()
 await expect(page.locator('.account-name')).toHaveText(bob)
 await page.unroute('**/api/command')
})
